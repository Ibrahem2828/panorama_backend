class Command(BaseCommand):
    help = "Create the default Arabic help texts for print options (idempotent; existing rows are never changed)."

    def handle(self, *args, **options):
        created = 0
        for order, (topic, key, title, body) in enumerate(HELP):
            _, was_created = PrintOptionHelp.objects.get_or_create(
                topic=str(topic),
                key=key,
                is_deleted=False,
                defaults={"title": title, "body": body, "sort_order": order, "is_active": True},
            )
            created += was_created
        self.stdout.write(f"print option help: created={created} existing={len(HELP) - created}")
